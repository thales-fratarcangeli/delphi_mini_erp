/* ===========================================================================
   ERP INDUSTRIAL - schema Firebird 5

   Convencao de nomes usada pelo mapeador (ver Infra.Mapping.pas):
     tabela  -> registrada explicitamente na Infra
     coluna  -> nome da PROPRIEDADE da entidade, em maiusculas
     chave   -> sempre ID, alimentada por um GENERATOR

   Tipos:
     Currency (Delphi) -> NUMERIC(15,4)
     Double            -> DOUBLE PRECISION
     TDateTime         -> TIMESTAMP
     enumerado         -> VARCHAR(20) com o nome RTTI (ex.: 'spConfirmado')
     Boolean           -> BOOLEAN (nativo desde o Firebird 3)

   Rode com:  isql -i bd/schema.sql
   ou pelo proprio sistema:  GestaoComercial.exe --dbcriar
   =========================================================================== */

