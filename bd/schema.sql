CREATE VIEW VW_ESTOQUE_CRITICO (CODIGO, DESCRICAO, TIPO, ESTOQUE,
  ESTOQUEMINIMO, FALTA, VALOR_REPOSICAO) AS
SELECT P.CODIGO, P.DESCRICAO, P.TIPO, P.ESTOQUE, P.ESTOQUEMINIMO,
       P.ESTOQUEMINIMO - P.ESTOQUE,
       (P.ESTOQUEMINIMO - P.ESTOQUE) * P.CUSTOMEDIO
  FROM PRODUTOS P
 WHERE P.ATIVO = TRUE
   AND P.ESTOQUE < P.ESTOQUEMINIMO;

/* A MESMA explosao de estrutura que o Delphi faz recursivamente, aqui
   resolvida pelo banco com WITH RECURSIVE. Vale comparar os dois codigos:
   Domain.Producao.Services -> TServicoEngenharia.ExplodirRecursivo */
CREATE VIEW VW_ESTRUTURA_EXPLODIDA (RAIZ_ID, NIVEL, COMPONENTE_ID, CODIGO,
  DESCRICAO, TIPO, QUANTIDADE) AS
WITH RECURSIVE ARVORE (RAIZ_ID, NIVEL, COMPONENTE_ID, QUANTIDADE) AS (
  SELECT E.PRODUTOPAIID, 0, E.COMPONENTEID,
         E.QUANTIDADE / (1 - E.PERDAPERCENTUAL)
    FROM ESTRUTURA_ITENS E
  UNION ALL
  SELECT A.RAIZ_ID, A.NIVEL + 1, F.COMPONENTEID,
         A.QUANTIDADE * (F.QUANTIDADE / (1 - F.PERDAPERCENTUAL))
    FROM ARVORE A
    JOIN ESTRUTURA_ITENS F ON F.PRODUTOPAIID = A.COMPONENTE_ID
   WHERE A.NIVEL < 12
)
SELECT A.RAIZ_ID, A.NIVEL, A.COMPONENTE_ID, P.CODIGO, P.DESCRICAO, P.TIPO,
       A.QUANTIDADE
  FROM ARVORE A
  JOIN PRODUTOS P ON P.ID = A.COMPONENTE_ID;

/* Eficiencia por centro de trabalho: previsto x realizado nas OPs. */
CREATE VIEW VW_EFICIENCIA_CENTRO (CODIGOCENTRO, OPERACOES, TEMPO_PREVISTO,
  TEMPO_REALIZADO, EFICIENCIA) AS
SELECT O.CODIGOCENTRO, COUNT(*), SUM(O.TEMPOPREVISTOMIN),
       SUM(O.TEMPOREALIZADOMIN),
       CASE WHEN SUM(O.TEMPOREALIZADOMIN) > 0
            THEN SUM(O.TEMPOPREVISTOMIN) / SUM(O.TEMPOREALIZADOMIN)
            ELSE 0 END
  FROM OP_OPERACOES O
 WHERE O.TEMPOREALIZADOMIN > 0
 GROUP BY O.CODIGOCENTRO;
